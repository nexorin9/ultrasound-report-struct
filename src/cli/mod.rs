//! **入口层**：命令行参数解析 + 运维通道（重放 / 自检）。
//!
//! 这一层是「**同一套主路径**」的命令面，不是第二套实现：
//!
//! | 子命令 | 落点 | 走的内核 |
//! |---|---|---|
//! | `init-db` | 建状态库 | [`crate::state::schema`] 幂等迁移 |
//! | `daemon` | **常驻监听**（事件驱动守护形态） | [`crate::daemon`] 调度器 + 处理器 |
//! | `parse` | 单份解析 | [`crate::parse`] 解析内核 |
//! | `ingest` | 批量受理新投递 | [`crate::ingest::ingest_inbox`] + 幂等闸 |
//! | `export` | 台账 / 失败清单导出 | [`crate::export`] |
//! | `replay` | **离线重放**（幂等键驱动） | [`crate::cli::replay`] |
//! | `selftest` | **一条命令出可核对结果** | [`crate::cli::selftest`] |
//!
//! **三条运维通道的分工**（不是同一个命令的三种叫法）：
//!
//! - `ingest` 受理**新投递**（幂等键没命中的才落库）；
//! - `replay` 重放**已入库**的报告 —— 词典改过之后，
//!   拿它对出「哪些报告的口径漂了」，确认后 `--apply` 补处理
//!   （**刷新**台账行，报告行不新增）；
//! - `selftest` 不碰业务数据（跑**内存库** + 内置资产），
//!   只回答「这套东西现在还是不是好的」。
//!
//! **全局参数**（三个子命令共用，语义只有一份）：
//!
//! | 参数 | 作用 |
//! |---|---|
//! | `--config <路径>` | 配置文件（路径与端点）；给了就跑启动自检 |
//! | `--state-db <路径>` | 状态库路径（覆盖配置文件与环境变量） |
//! | `--dry-run` | **演练模式**：照常解析与统计，**不落状态库、不写出站报文** |
//! | `--require-credentials` | 按**守护档**要求凭据齐备（缺项逐条列出并非零退出） |
//!
//! **`--dry-run` 的边界**：它只保证**不落库**。
//! 已经发出的请求收不回来 —— 所以演练模式**不覆盖出站写**，
//! 需要看「会不会发出去」时用 `selftest` 或 `replay --dry-run`。

pub mod args;
pub mod replay;
pub mod selftest;

